#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["pyyaml"]
# ///
"""Project and diff the site Merged-Brewfile (Phase F4 / step1 §4.3).

Reads brew/fragments/*.yml (stack claims), writes generated/Merged-Brewfile,
and optionally diffs against the system-state Brewfile snapshot.

Never runs brew install/uninstall/bundle cleanup.

Usage (from repo root):
  bin/project_merged_brewfile.py project
  bin/project_merged_brewfile.py diff [--strict]
  bin/project_merged_brewfile.py both [--strict]
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
FRAGMENTS_DIR = REPO / "brew" / "fragments"
OUT_PATH = REPO / "generated" / "Merged-Brewfile"

# brew "name"  or  brew "name", restart_service: :changed
BREWFILE_TOKEN_RE = re.compile(
    r"""^(?P<kind>tap|brew|cask)\s+"(?P<name>[^"]+)" """,
    re.MULTILINE,
)

GENERATED_HEADER = """\
# GENERATED by bin/project_merged_brewfile.py — do not hand-edit.
# Source of truth: brew/fragments/*.yml
# Project: just brew-project
# Diff vs live snapshot: just brew-diff
# This file is visibility only; it does NOT auto-uninstall packages.
# Destructive brew bundle cleanup requires operator sign-off.
"""


def die(msg: str, code: int = 2) -> None:
    print(f"merged-brewfile: FAIL: {msg}", file=sys.stderr)
    raise SystemExit(code)


def load_fragments() -> list[dict]:
    if not FRAGMENTS_DIR.is_dir():
        die(f"missing fragments dir: {FRAGMENTS_DIR}")
    paths = sorted(FRAGMENTS_DIR.glob("*.yml")) + sorted(FRAGMENTS_DIR.glob("*.yaml"))
    if not paths:
        die(f"no fragment files in {FRAGMENTS_DIR}")
    fragments: list[dict] = []
    for path in paths:
        try:
            data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        except (OSError, yaml.YAMLError) as exc:
            die(f"cannot parse {path}: {exc}")
        if not isinstance(data, dict):
            die(f"{path}: root must be a mapping")
        stack = data.get("stack")
        if not stack or not isinstance(stack, str):
            die(f"{path}: missing string field 'stack'")
        data["_path"] = str(path.relative_to(REPO))
        fragments.append(data)
    return fragments


def _entries(kind_list: object) -> list[dict]:
    if not kind_list:
        return []
    out: list[dict] = []
    for item in kind_list:
        if isinstance(item, str):
            out.append({"name": item})
        elif isinstance(item, dict) and "name" in item:
            out.append(item)
        else:
            die(f"invalid entry {item!r} (want string or {{name: ...}})")
    return out


def normalize_name(name: str) -> str:
    """Collapse tap-qualified names for matching (vector vs vectordotdev/brew/vector)."""
    name = name.strip()
    if name.count("/") >= 2:
        # tap/user/formula → last component
        return name.rsplit("/", 1)[-1]
    if "/" in name and not name.startswith("@"):
        # might be cask "user/tap/name" style — keep last segment
        parts = name.split("/")
        if len(parts) == 3:
            return parts[-1]
    return name


def collect_claims(fragments: list[dict]) -> dict[str, dict[str, dict]]:
    """Return {kind: {canonical_name: claim_meta}} for taps/formulae/casks."""
    claims: dict[str, dict[str, dict]] = {
        "tap": {},
        "brew": {},
        "cask": {},
    }
    collisions: list[str] = []

    for frag in fragments:
        stack = frag["stack"]
        src = frag["_path"]
        for tap in _entries(frag.get("taps")):
            name = tap["name"]
            key = name  # taps keep full name
            meta = {
                "name": name,
                "stack": stack,
                "source": src,
                "note": tap.get("note") or frag.get("description") or "",
                "url": tap.get("url"),
            }
            prev = claims["tap"].get(key)
            if prev and prev["stack"] != stack:
                collisions.append(f"tap {name!r}: {prev['stack']} vs {stack}")
            claims["tap"][key] = meta

        for formula in _entries(frag.get("formulae")):
            name = formula["name"]
            key = normalize_name(name)
            aliases = formula.get("also_match") or formula.get("aliases") or []
            if isinstance(aliases, str):
                aliases = [aliases]
            meta = {
                "name": name,
                "stack": stack,
                "source": src,
                "note": formula.get("note") or "",
                "also_match": [str(a) for a in aliases],
            }
            prev = claims["brew"].get(key)
            if prev and prev["stack"] != stack:
                # Overlap is harmless for install (step1); warn but last-writer by stack order
                collisions.append(
                    f"formula {key!r}: claimed by both {prev['stack']} and {stack} "
                    f"(allowed; annotated with both via first-seen stack={prev['stack']})"
                )
                # Keep first claim as primary owner for annotation
                continue
            claims["brew"][key] = meta

        for cask in _entries(frag.get("casks")):
            name = cask["name"]
            key = normalize_name(name)
            meta = {
                "name": name,
                "stack": stack,
                "source": src,
                "note": cask.get("note") or "",
            }
            prev = claims["cask"].get(key)
            if prev and prev["stack"] != stack:
                collisions.append(
                    f"cask {key!r}: claimed by both {prev['stack']} and {stack}"
                )
                continue
            claims["cask"][key] = meta

    for c in collisions:
        # Formula overlap is expected/harmless; print as notice, not fail.
        print(f"merged-brewfile: note: {c}", file=sys.stderr)
    return claims


def render_brewfile(fragments: list[dict], claims: dict[str, dict[str, dict]]) -> str:
    lines: list[str] = [GENERATED_HEADER.rstrip(), ""]

    # Group by stack for readability
    by_stack: dict[str, dict[str, list[dict]]] = defaultdict(
        lambda: {"tap": [], "brew": [], "cask": []}
    )
    stack_order: list[str] = []
    for frag in fragments:
        st = frag["stack"]
        if st not in stack_order:
            stack_order.append(st)

    for kind in ("tap", "brew", "cask"):
        for meta in claims[kind].values():
            by_stack[meta["stack"]][kind].append(meta)

    for stack in stack_order:
        groups = by_stack.get(stack)
        if not groups:
            continue
        frag = next(f for f in fragments if f["stack"] == stack)
        desc = (frag.get("description") or "").strip().replace("\n", " ")
        lines.append(f"# === stack: {stack} ===")
        if desc:
            lines.append(f"# {desc}")
        lines.append(f"# fragment: {frag['_path']}")
        lines.append("")

        for meta in sorted(groups["tap"], key=lambda m: m["name"].lower()):
            note = f"  # {meta['note']}" if meta.get("note") else ""
            if meta.get("url"):
                lines.append(f'tap "{meta["name"]}", "{meta["url"]}"{note}')
            else:
                lines.append(f'tap "{meta["name"]}"{note}')

        for meta in sorted(groups["brew"], key=lambda m: m["name"].lower()):
            note = f"  # [{stack}] {meta['note']}".rstrip() if meta.get("note") else f"  # [{stack}]"
            lines.append(f'brew "{meta["name"]}"{note}')

        for meta in sorted(groups["cask"], key=lambda m: m["name"].lower()):
            note = f"  # [{stack}] {meta['note']}".rstrip() if meta.get("note") else f"  # [{stack}]"
            lines.append(f'cask "{meta["name"]}"{note}')

        lines.append("")

    # Summary footer
    n_tap = len(claims["tap"])
    n_brew = len(claims["brew"])
    n_cask = len(claims["cask"])
    lines.append(
        f"# summary: {n_tap} taps, {n_brew} formulae, {n_cask} casks "
        f"across {len(stack_order)} stack(s)"
    )
    lines.append("")
    return "\n".join(lines)


def cmd_project() -> int:
    fragments = load_fragments()
    claims = collect_claims(fragments)
    text = render_brewfile(fragments, claims)
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    prev = OUT_PATH.read_text(encoding="utf-8") if OUT_PATH.exists() else None
    OUT_PATH.write_text(text, encoding="utf-8")
    status = "unchanged" if prev == text else ("updated" if prev is not None else "created")
    print(
        f"merged-brewfile: {status} {OUT_PATH.relative_to(REPO)} "
        f"({len(claims['tap'])} taps, {len(claims['brew'])} formulae, "
        f"{len(claims['cask'])} casks)"
    )
    return 0


def resolve_snapshot() -> Path:
    import os

    override = os.environ.get("SITE_BREW_SNAPSHOT")
    candidates = []
    if override:
        candidates.append(Path(override).expanduser())
    home = Path.home()
    candidates.extend(
        [
            home / "system-state" / "Brewfile",
            Path("/opt/homebrew/var/system-state/Brewfile"),
            Path("/usr/local/var/system-state/Brewfile"),
        ]
    )
    for p in candidates:
        if p.is_file():
            return p
    die(
        "no live Brewfile snapshot found; looked for "
        + ", ".join(str(c) for c in candidates)
        + " (set SITE_BREW_SNAPSHOT to override)"
    )
    raise AssertionError("unreachable")


def parse_brewfile_tokens(text: str) -> dict[str, set[str]]:
    found: dict[str, set[str]] = {"tap": set(), "brew": set(), "cask": set()}
    for line in text.splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        m = re.match(r'^(tap|brew|cask)\s+"([^"]+)"', s)
        if not m:
            continue
        kind, name = m.group(1), m.group(2)
        if kind == "tap":
            found["tap"].add(name)
        else:
            found[kind].add(normalize_name(name))
            # also keep full name for matching
            found[kind].add(name)
    return found


def cmd_diff(*, strict: bool) -> int:
    # Ensure projection is current
    fragments = load_claims_and_project()
    claims = collect_claims(fragments)
    snap_path = resolve_snapshot()
    snap_text = snap_path.read_text(encoding="utf-8")
    live = parse_brewfile_tokens(snap_text)

    missing: list[str] = []
    present: list[str] = []

    for kind, label in (("tap", "tap"), ("brew", "formula"), ("cask", "cask")):
        for key, meta in sorted(claims[kind].items(), key=lambda kv: kv[0].lower()):
            names = {key, meta["name"], normalize_name(meta["name"])}
            for a in meta.get("also_match") or []:
                names.add(a)
                names.add(normalize_name(a))
            # Homebrew keg naming: claim "python" matches live python@3.12 etc.
            if kind == "brew" and meta["name"] == "python":
                names.update(
                    n for n in live["brew"] if n == "python" or n.startswith("python@")
                )
            if names & live[kind]:
                present.append(f"  OK  {label} {meta['name']} [{meta['stack']}]")
            else:
                missing.append(
                    f"  MISSING  {label} {meta['name']} [{meta['stack']}] "
                    f"— {meta.get('note') or meta['source']}"
                )

    # Live-only (informational): tokens in snapshot not in any claim
    claimed_norm: dict[str, set[str]] = {
        "tap": set(claims["tap"].keys()) | {m["name"] for m in claims["tap"].values()},
        "brew": set(claims["brew"].keys())
        | {m["name"] for m in claims["brew"].values()}
        | {normalize_name(m["name"]) for m in claims["brew"].values()},
        "cask": set(claims["cask"].keys())
        | {m["name"] for m in claims["cask"].values()}
        | {normalize_name(m["name"]) for m in claims["cask"].values()},
    }
    for m in claims["brew"].values():
        for a in m.get("also_match") or []:
            claimed_norm["brew"].add(a)
            claimed_norm["brew"].add(normalize_name(a))
        if m["name"] == "python":
            claimed_norm["brew"].update(
                n for n in live["brew"] if n == "python" or n.startswith("python@")
            )
    live_only: list[str] = []
    # Re-parse for display names only (primary token per line)
    for line in snap_text.splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        m = re.match(r'^(tap|brew|cask)\s+"([^"]+)"', s)
        if not m:
            continue
        kind, name = m.group(1), m.group(2)
        candidates = {name, normalize_name(name)}
        if not (candidates & claimed_norm[kind]):
            live_only.append(f"  live-only  {kind} {name}")

    print(f"merged-brewfile: diff vs {snap_path}")
    print(f"merged-brewfile: claimed present on live: {len(present)}")
    print(f"merged-brewfile: claimed missing on live: {len(missing)}")
    print(f"merged-brewfile: live-only (unclaimed) lines: {len(live_only)}")
    if missing:
        print("\n# Claimed packages missing from live snapshot:")
        for row in missing:
            print(row)
    if live_only:
        print("\n# Live snapshot packages not claimed by any fragment (informational):")
        # Cap noise: show count + first 30
        for row in live_only[:30]:
            print(row)
        if len(live_only) > 30:
            print(f"  … and {len(live_only) - 30} more")
    print(
        "\nmerged-brewfile: no brew installs/uninstalls performed "
        "(read-only diff; cleanup needs operator gate)"
    )

    if strict and missing:
        print("merged-brewfile: --strict: failing due to missing claims", file=sys.stderr)
        return 1
    return 0


def load_claims_and_project() -> list[dict]:
    fragments = load_fragments()
    claims = collect_claims(fragments)
    text = render_brewfile(fragments, claims)
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(text, encoding="utf-8")
    return fragments


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "command",
        choices=("project", "diff", "both"),
        help="project: write Merged-Brewfile; diff: compare to live snapshot; both: project then diff",
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="with diff: exit 1 if any claimed package is missing from the live snapshot",
    )
    args = parser.parse_args()

    if args.command == "project":
        return cmd_project()
    if args.command == "diff":
        return cmd_diff(strict=args.strict)
    # both
    rc = cmd_project()
    if rc != 0:
        return rc
    return cmd_diff(strict=args.strict)


if __name__ == "__main__":
    raise SystemExit(main())
